CREATE TABLE IF NOT EXISTS barang (
    id_barang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    nama_barang VARCHAR(200) NOT NULL,
    stok INTEGER NOT NULL DEFAULT 0 CHECK (stok >= 0),
    harga_pokok NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (harga_pokok >= 0),
    harga_jual NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (harga_jual >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pelanggan (
    id_pelanggan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pelanggan VARCHAR(150) NOT NULL,
    kontak VARCHAR(50),
    alamat TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS supplier (
    id_supplier BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_supplier VARCHAR(150) NOT NULL,
    kontak VARCHAR(50),
    alamat TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transaksi_pembelian (
    id_pembelian BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_faktur VARCHAR(100) NOT NULL UNIQUE,
    id_supplier BIGINT NOT NULL REFERENCES supplier(id_supplier) ON DELETE RESTRICT,
    total_bayar NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_bayar >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transaksi_penjualan (
    id_penjualan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_nota VARCHAR(100) NOT NULL UNIQUE,
    id_pelanggan BIGINT NOT NULL REFERENCES pelanggan(id_pelanggan) ON DELETE RESTRICT,
    total_bayar NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_bayar >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS penyesuaian_stok (
    id_penyesuaian BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barang BIGINT NOT NULL REFERENCES barang(id_barang) ON DELETE RESTRICT,
    jenis_penyesuaian VARCHAR(10) NOT NULL CHECK (jenis_penyesuaian IN ('Tambah', 'Kurang')),
    jumlah INTEGER NOT NULL CHECK (jumlah > 0),
    keterangan TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detail_pembelian (
    id_detail_pembelian BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pembelian BIGINT NOT NULL REFERENCES transaksi_pembelian(id_pembelian) ON DELETE CASCADE,
    id_barang BIGINT NOT NULL REFERENCES barang(id_barang) ON DELETE RESTRICT,
    jumlah INTEGER NOT NULL CHECK (jumlah > 0),
    harga_satuan NUMERIC(14,2) NOT NULL CHECK (harga_satuan >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detail_penjualan (
    id_detail_penjualan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_penjualan BIGINT NOT NULL REFERENCES transaksi_penjualan(id_penjualan) ON DELETE CASCADE,
    id_barang BIGINT NOT NULL REFERENCES barang(id_barang) ON DELETE RESTRICT,
    jumlah INTEGER NOT NULL CHECK (jumlah > 0),
    harga_satuan NUMERIC(14,2) NOT NULL CHECK (harga_satuan >= 0),
    hpp_satuan NUMERIC(14,2) NOT NULL CHECK (hpp_satuan >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS jurnal_umum (
    id_jurnal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    akun VARCHAR(150) NOT NULL,
    debit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    kredit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (kredit >= 0),
    no_bukti VARCHAR(100) NOT NULL,
    keterangan TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_transaksi_pembelian_supplier
    ON transaksi_pembelian(id_supplier);
CREATE INDEX IF NOT EXISTS idx_transaksi_penjualan_pelanggan
    ON transaksi_penjualan(id_pelanggan);
CREATE INDEX IF NOT EXISTS idx_penyesuaian_stok_barang
    ON penyesuaian_stok(id_barang);
CREATE INDEX IF NOT EXISTS idx_detail_pembelian_transaksi
    ON detail_pembelian(id_pembelian);
CREATE INDEX IF NOT EXISTS idx_detail_pembelian_barang
    ON detail_pembelian(id_barang);
CREATE INDEX IF NOT EXISTS idx_detail_penjualan_transaksi
    ON detail_penjualan(id_penjualan);
CREATE INDEX IF NOT EXISTS idx_detail_penjualan_barang
    ON detail_penjualan(id_barang);
CREATE INDEX IF NOT EXISTS idx_jurnal_umum_no_bukti
    ON jurnal_umum(no_bukti);
